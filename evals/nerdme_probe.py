"""Stage-1 probe: can typed README spans supply the anchor channel where manifests cannot?

NR-39 left the anchor channel in a specific state: it is the **only** repository-side
channel that discriminates (20.5% / 14.9% / 6.7% of abstracts at score-3 / actionable /
below name an anchor, against keywords which fire on 97.6% / 96.4% / 97.4% and are
therefore noise) -- and it does not exist for **12 of 25** cases, because
``_extract_anchors`` reads ``requirements.txt``, ``pyproject.toml``, ``setup.py`` and
``package.json`` only, so a C, C++, Rust or Go repository has nothing to parse.

NERdME (arXiv:2603.05750) proposes the mechanism this gap wants: typed, **verbatim-span**
entity extraction over README files. This probe tests whether that mechanism supplies
anchors that are worth having, before anything is built.

**The lesson this probe is designed around is NR-36, not NR-39.** Source scanning also
fixed anchor coverage -- 24/25 cases gained anchors, 8 of them from zero -- and then
measured **-0.52 net@2**. Its per-field dump shows why: `thin-kv` acquired `grafanalib`
and `executor_panels`, its Grafana dashboards rather than its storage engine. So *count of
anchors gained* is a discredited headline: this probe's primary metric is the anchor
channel's **discrimination**, and a treatment that buys coverage by diluting the signal is
a failure here even if every zero-anchor case gains terms.

The precise danger, stated so it can be measured: README-derived spans may simply behave
like README *keywords*, which the same instrument already scores at +0.2pt -- noise. The
anchor channel's whole value is that it separates; extraction that lands near the keyword
gap has converted a discriminating channel into a non-discriminating one.

PRE-REGISTERED, written before the first run (evals/RESULTS.md keeps the record):

  Q1  COVERAGE. Of the 12 zero-anchor cases, 10-12 gain at least one typed span. High
      confidence: these repositories name their libraries in prose even when they carry
      no manifest the profiler can read.

  Q2  DISCRIMINATION -- primary. Gap = (score-3 abstract-hit %) - (below-2 %).
      Manifest baseline +13.8pt; keywords +0.2pt. I predict the union lands at
      **+6 to +12pt**: below baseline, because 13 previously untested repositories enter
      and because READMEs name rivals as well as dependencies ("faster than RocksDB"),
      which fires on non-actionable papers too; but well clear of keyword noise, because
      typed spans are proper nouns rather than TF-IDF topic words.
      **KILL CONDITION: union gap < +7.0pt.** That is half the baseline, and it would mean
      coverage was bought with the channel's only virtue -- the NR-36 shape a second time.

  Q3  GROUNDED COVERAGE. Anchor+relation on actionable papers rises from 12.3% to 20-32%.

  Q4  CONCENTRATION. Cases with at least one grounded claim rise from 7 to 14-20, and the
      top-4 share of all grounded claims falls below 70% (baseline: 93%).

  Q5  SECONDARY, the alias-table bridge. NR-39's revival condition is a table mapping
      observable repo facts to the names abstracts use (`faiss` -> IVF-PQ, product
      quantization). If `method`-typed spans are extracted on >=15 cases AND their
      discrimination gap is at least the `library`-typed gap, then part of that table is
      obtainable by extraction rather than curation, and the ForeCite probe's scope
      shrinks. This is reported, never used to justify the primary verdict.

POST-HOC, added after the first run and an adversarial audit of it. These are repairs, not
predictions, and nothing they produce carries the weight of a pre-registered result:

  Q2b THE JOIN. The first version computed Q1 over the zero-anchor repos and Q2 over ALL
      repos and never intersected them, so its +36.3pt headline was generated by
      repositories whose manifests already parse -- the ones the feature is NOT for. The
      split is now reported, and the verdict is taken on the rescued subset.

  Q2c A COMPARATOR OFF ITS CEILING. "Keywords score +0.2pt, therefore keywords are noise"
      -- inherited from NR-39 -- is a saturation artifact. There are ~19 keywords per case
      against ~4 spans, so nearly every abstract contains at least one and a binary hit
      metric cannot move. The control now samples |spans| keywords per case.

  PER-CASE ESTIMATORS THROUGHOUT. The first version pooled 1,237 papers into one rate.
      `peft` alone supplies 23% of all score-3 papers at a 100% hit rate, so the pooled
      figure was close to a report about `peft`. Every gap is now shown four ways --
      pooled, unweighted macro, macro over cases with >=5 papers per stratum, and
      Mantel-Haenszel -- because they disagree, and the disagreement IS the finding. M-H
      governs the verdict: unweighted macro lets `columnar` (ONE score-3 paper, +84.2pt)
      outvote `storage` (twenty-one).

A KNOWN EXTRACTION DEFECT, reported rather than patched: MIN_ANCHOR_LEN is 3, inherited
from relation_probe so the baseline and treatment obey identical rules. That admits the
span `age` (from `age-plugin-pq` in `encryption`), which matches ordinary English and
fires on 16 below-2 abstracts -- the single largest false-positive source. Raising the
floor for prose spans while leaving it for package names would make the two channels
incomparable, so the defect is left visible in the false-positive dump instead.

Extraction is cached, so only the first run costs anything (~$0.02, 25 Haiku calls over
READMEs). Everything downstream reads cached artifacts, exactly as relation_probe.py does.

    uv run python evals/nerdme_probe.py            # extract (once) + analyse
    uv run python evals/nerdme_probe.py --report   # analyse only, $0, fails if no cache
"""

