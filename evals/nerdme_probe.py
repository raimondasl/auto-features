# The profiler's own README search order. Imported behaviour would be better, but the
# profiler exposes no "find the README" helper -- so the list is duplicated here and
# asserted against the profiler's source at test time rather than left to drift silently.
README_NAMES = ("README.md", "README.rst", "README.txt", "README")

# NERdME defines 10 entity types; the abstract does not enumerate them and the dataset's
# availability is not stated on the abstract page, so this is NOT a replication of its
# schema. These five are chosen for the ANCHOR role specifically: things a paper's
# abstract might name when it improves on them.
ENTITY_TYPES = ("library", "method", "format", "model", "dataset")

# Budget per README. The profiler itself budgets prose at 300 chars for the gate; this is
# a different job -- extraction wants the whole document -- but an unbounded read would
# put a 41k-character README in a prompt, so it is capped.
README_BUDGET = 12_000

PROMPT = """\
You are extracting named entities from a software repository's README, to answer one \
question: which named things does THIS repository actually depend on, implement, or \
build upon?

Return only entities that are CENTRAL to what the repository itself is or does.

Do NOT return:
- systems the README merely compares against or benchmarks rivals to
- documentation, CI, packaging, linting or test tooling
- generic topic words ("machine learning", "database", "performance")
- anything not written literally in the text below

Entity types:
- library:  a named software library, framework or engine it uses or builds on
- method:   a named algorithm or technique it implements (e.g. "IVF-PQ", "MVCC")
- format:   a named data format, protocol or wire encoding
- model:    a named model or architecture
- dataset:  a named dataset

Each span must be copied VERBATIM from the README -- the exact substring, not a \
paraphrase, expansion or correction of it.

Return JSON only, no prose:
{{"entities": [{{"span": "<verbatim>", "type": "<one of the five>"}}]}}

At most 40 entities. If the README names none, return {{"entities": []}}.

README of the repository "{case}":
---
{readme}
---
"""


def _read_readme(repo_dir: Path) -> str:
    for name in README_NAMES:
        text = _read_text_file(repo_dir / name)
        if text:
            return text[:README_BUDGET]
    return ""


def _parse_entities(raw: str) -> list[dict[str, str]]:
    """Pull the JSON object out of a model reply, tolerating fences and stray prose."""
    text = raw.strip()
    if text.startswith("```"):
        text = re.sub(r"^```(?:json)?\s*|\s*```$", "", text, flags=re.MULTILINE).strip()
    start, end = text.find("{"), text.rfind("}")
    if start == -1 or end == -1:
        return []
    try:
        data = json.loads(text[start : end + 1])
    except json.JSONDecodeError:
        return []
    out = []
    for e in data.get("entities", []):
        span, etype = str(e.get("span", "")).strip(), str(e.get("type", "")).strip().lower()
        if span and etype in ENTITY_TYPES:
            out.append({"span": span, "type": etype})
    return out


def extract(cases: list[str], *, refresh: bool = False) -> dict[str, Any]:
    """Extract typed spans per case, cached. The only stage that costs money."""
    cached: dict[str, Any] = {}
    if CACHE.exists() and not refresh:
        cached = json.loads(CACHE.read_text(encoding="utf-8"))

    cfg = SuggestionsConfig(provider="claude", claude_model="claude-haiku-4-5", timeout=60)
    todo = [c for c in cases if c not in cached]
    if todo:
        print(f"Extracting typed spans for {len(todo)} case(s) (~$0.02 total)...")
    for case in todo:
        readme = _read_readme(WORK / case)
        if not readme:
            cached[case] = {"entities": [], "readme_chars": 0, "note": "no README found"}
            print(f"  {case:12} no README")
            continue
        try:
            raw = complete(
                PROMPT.format(case=case, readme=readme), cfg, max_tokens=2000, max_retries=2
            )
        except LLMError as exc:
            print(f"  {case:12} FAILED: {exc}")
            continue
        ents = _parse_entities(raw)
        # Verbatim discipline (NR-12): a span that is not literally in the README is a
        # hallucination, not an anchor. Recorded rather than silently dropped -- the
        # spurious rate is a result of this probe, not a nuisance.
        low = readme.lower()
        kept = [e for e in ents if e["span"].lower() in low]
        cached[case] = {
            "entities": kept,
            "hallucinated": [e for e in ents if e["span"].lower() not in low],
            "readme_chars": len(readme),
        }
        print(f"  {case:12} {len(kept):>3} spans kept, {len(ents) - len(kept)} not verbatim")
        CACHE.write_text(json.dumps(cached, indent=1), encoding="utf-8")
    CACHE.write_text(json.dumps(cached, indent=1), encoding="utf-8")
    return cached


def _spans_as_anchors(entry: dict[str, Any], types: tuple[str, ...] = ENTITY_TYPES) -> set[str]:
    """Typed spans, filtered by the same rules the baseline anchor set obeys.

    Applying STOPWORD_ANCHORS and MIN_ANCHOR_LEN here is what makes the comparison fair:
    without it the treatment would be scored on terms the baseline is forbidden.
    """
    out = set()
    for e in entry.get("entities", []):
        if e["type"] not in types:
            continue
        span = e["span"].lower().strip()
        if len(span) >= MIN_ANCHOR_LEN and span not in STOPWORD_ANCHORS:
            out.add(span)
    return out


def _stratify(rows: list[dict[str, Any]]) -> tuple[list, list, list]:
    return (
        [r for r in rows if r["score"] >= 3],
        [r for r in rows if r["score"] >= ACTIONABLE],
        [r for r in rows if r["score"] < ACTIONABLE],
    )


def _hit_pct(sub: list[dict[str, Any]], key: str) -> float:
    return 100 * sum(1 for r in sub if r[key]) / len(sub) if sub else 0.0


# --------------------------------------------------------------------------------------
# Per-case estimators.
#
# The pooled hit rate the first version of this probe reported is the one number that must
# never stand alone: `peft` supplies 23% of all score-3 papers at a 100% hit rate, so a
# pooled figure is close to a report about `peft`. Everything below compares WITHIN a case
# first and combines afterwards, which is what stops one repository deciding the answer.
# --------------------------------------------------------------------------------------

Cells = dict[str, tuple[int, int, int, int]]


def _case_cells(rows: list[dict[str, Any]], key: str) -> Cells:
    """Per case: (hits among score-3, n score-3, hits among below-2, n below-2)."""
    cells: dict[str, list[int]] = {}
    for r in rows:
        c = cells.setdefault(r["case"], [0, 0, 0, 0])
        if r["score"] >= 3:
            c[1] += 1
            c[0] += 1 if r[key] else 0
        elif r["score"] < ACTIONABLE:
            c[3] += 1
            c[2] += 1 if r[key] else 0
    return {c: (v[0], v[1], v[2], v[3]) for c, v in cells.items()}


def _usable(cells: Cells) -> Cells:
    """Cases with at least one paper in BOTH strata -- the only ones that carry a gap."""
    return {c: v for c, v in cells.items() if v[1] > 0 and v[3] > 0}


def _case_gaps(cells: Cells) -> dict[str, float]:
    return {c: 100 * (a / n1) - 100 * (b / n0) for c, (a, n1, b, n0) in _usable(cells).items()}


def _macro(cells: Cells, min_n: int = 0) -> float:
    """Every case counts once, regardless of how many papers it contributed.

    *min_n* drops cases with fewer than that many papers in either stratum. Unweighted
    macro is not automatically the honest estimator: `columnar` has ONE score-3 paper, so
    its gap is +84.2pt or -15.8pt depending on that single paper, and an unfiltered mean
    lets that outweigh a case with 21. Report it both ways or not at all.
    """
    g = {c: v for c, v in _case_gaps(cells).items() if min(cells[c][1], cells[c][3]) >= min_n}
    return sum(g.values()) / len(g) if g else 0.0


def _n_positive(cells: Cells, min_n: int = 0) -> tuple[int, int]:
    """(cases with a gap > 0, cases counted) -- how broad the effect is, not how large."""
    g = {c: v for c, v in _case_gaps(cells).items() if min(cells[c][1], cells[c][3]) >= min_n}
    return sum(1 for v in g.values() if v > 0), len(g)


def _mh(cells: Cells) -> float:
    """Mantel-Haenszel weighted risk difference: compare inside each case, then combine.

    Weight w = n1*n0/(n1+n0) is the standard MH weight for a risk difference. It gives a
    case influence in proportion to how much it can actually resolve, rather than in
    proportion to how many papers it happened to contribute to one stratum.
    """
    num = den = 0.0
    for a, n1, b, n0 in _usable(cells).values():
        w = n1 * n0 / (n1 + n0)
        num += w * (a / n1 - b / n0)
        den += w
    return 100 * num / den if den else 0.0


def _bootstrap_ci(cells: Cells, draws: int = 2000, seed: int = 20260816) -> tuple[float, float]:
    """Percentile CI for the macro gap, resampling CASES -- the unit of independence.

    Papers within a case share a repository profile and a pool, so resampling papers would
    understate the interval. The 25 cases are what vary.
    """
    gaps = list(_case_gaps(cells).values())
    if len(gaps) < 2:
        return (0.0, 0.0)
    rng = random.Random(seed)
    means = []
    for _ in range(draws):
        sample = [gaps[rng.randrange(len(gaps))] for _ in gaps]
        means.append(sum(sample) / len(sample))
    means.sort()
    return (means[int(0.025 * draws)], means[int(0.975 * draws)])


def _loo_worst(cells: Cells) -> tuple[str, float]:
    """The case whose removal moves the macro gap most: names the load-bearing repo."""
    base = _macro(cells)
    worst, worst_delta = "", 0.0
    for c in _usable(cells):
        d = _macro({k: v for k, v in cells.items() if k != c}) - base
        if abs(d) > abs(worst_delta):
            worst, worst_delta = c, d
    return worst, worst_delta


def _sign(cells: Cells) -> str:
    g = list(_case_gaps(cells).values())
    pos = sum(1 for v in g if v > 0)
    neg = sum(1 for v in g if v < 0)
    return f"{pos}/{neg}/{sum(1 for v in g if v == 0)}"


def _build_rows(spans: dict[str, Any], cases: list[str]) -> tuple[list, list, dict]:
    rows: list[dict[str, Any]] = []
    per_case: list[dict[str, Any]] = []
    kw_by_case: dict[str, set[str]] = {}
    for case in cases:
        manifest, keywords = _repo_terms(case)
        entry = spans.get(case, {})
        nerdme = _spans_as_anchors(entry)
        kw_by_case[case] = keywords
        abstracts = _pool_abstracts(case)
        for pid, verdict in _verdicts(case).items():
            paper = abstracts.get(pid)
            if paper is None:
                continue
            abstract = f"{paper.get('title', '')} {paper.get('abstract', '')}"
            rows.append(
                {
                    "case": case,
                    "score": int(verdict.get("score", 0)),
                    "abstract": abstract,
                    "abs_manifest": _mentions(abstract, manifest),
                    "abs_nerdme": _mentions(abstract, nerdme),
                    "abs_union": _mentions(abstract, manifest | nerdme),
                    "abs_keywords": _mentions(abstract, keywords),
                    "abs_method": _mentions(abstract, _spans_as_anchors(entry, ("method",))),
                    "abs_library": _mentions(abstract, _spans_as_anchors(entry, ("library",))),
                    "relations": _relations(abstract),
                }
            )
        per_case.append(
            {
                "case": case,
                "manifest": len(manifest),
                "nerdme": len(nerdme),
                "union": len(manifest | nerdme),
                "methods": len(_spans_as_anchors(entry, ("method",))),
                "zero_before": len(manifest) == 0,
                "rescued": len(manifest) == 0 and len(nerdme) > 0,
                "hallucinated": len(entry.get("hallucinated", [])),
                "entities": len(entry.get("entities", [])),
            }
        )
    return rows, per_case, kw_by_case


def analyse(spans: dict[str, Any]) -> int:
    cases = sorted(p.stem for p in POOL.glob("*.json"))
    if not cases:
        raise SystemExit(f"no frozen pools under {POOL}; this probe reads cached artifacts only")

    rows, per_case, kw_by_case = _build_rows(spans, cases)
    if sum(c["nerdme"] for c in per_case) == 0:
        raise SystemExit(
            "every case extracted 0 typed spans: the extractor is broken, not the corpus. "
            "Reporting 0% hits here would be void read as null."
        )

    top, good, bad = _stratify(rows)
    print("NERdME probe (P9) -- typed README spans as an anchor channel\n")
    print(f"  {len(cases)} cases, {len(rows)} judged papers with an abstract in the pool")
    print(f"  {len(good)} actionable (>= {ACTIONABLE}), {len(top)} at 3, {len(bad)} below\n")

    # ---- Q1 coverage: pre-registered, and the one result the judge cannot touch ----
    zero_before = [c["case"] for c in per_case if c["zero_before"]]
    rescued = [c["case"] for c in per_case if c["rescued"]]
    still_zero = [c["case"] for c in per_case if c["union"] == 0]
    print("Q1  COVERAGE  [pre-registered: 10-12 of the zero-anchor cases gain spans]\n")
    print(f"  no manifest anchor:      {len(zero_before):>2}  {zero_before}")
    print(f"  of those, gained spans:  {len(rescued):>2}  {rescued}")
    print(f"  still no anchor at all:  {len(still_zero):>2}  {still_zero}")
    ent = sum(c["entities"] for c in per_case)
    hal = sum(c["hallucinated"] for c in per_case)
    tot = ent + hal
    print(f"  spans {tot}, non-verbatim {hal} = {100 * hal / tot if tot else 0:.1f}% spurious")
    hit = "PASS" if len(rescued) >= 10 else "MISS"
    print(f"  VERDICT: {hit} - got {len(rescued)}, wanted 10-12\n")

    # ---- Q2 discrimination: pooled shown only beside the per-case estimators -------
    print("Q2  DISCRIMINATION  [pre-registered primary; KILL if gap < +7.0pt]\n")
    print(
        f"  {'channel':10} {'pooled':>8} {'macro':>8} {'mac>=5':>8} {'M-H':>8} "
        f"{'95% CI (cases)':>19} {'+/-/=':>9}"
    )
    cells: Cells = {}
    all_cells: dict[str, Cells] = {}
    for label, key in (
        ("manifest", "abs_manifest"),
        ("nerdme", "abs_nerdme"),
        ("union", "abs_union"),
        ("keywords", "abs_keywords"),
    ):
        cl = _case_cells(rows, key)
        all_cells[label] = cl
        lo, hi = _bootstrap_ci(cl)
        pooled = _hit_pct(top, key) - _hit_pct(bad, key)
        print(
            f"  {label:10} {pooled:>+7.1f} {_macro(cl):>+7.1f} {_macro(cl, 5):>+7.1f} "
            f"{_mh(cl):>+7.1f}  [{lo:>+6.1f},{hi:>+6.1f}] {_sign(cl):>9}"
        )
    cells = all_cells["nerdme"]
    print(f"\n  usable cases (papers in BOTH strata): {len(_usable(cells))} of {len(cases)}")
    for label in ("manifest", "nerdme"):
        c, dlt = _loo_worst(all_cells[label])
        print(f"  {label:9} load-bearing case: {c or 'n/a'} (removing it moves macro {dlt:+.1f}pt)")
    print()

    # ---- Q2b the join. POST-HOC repair, and the verdict that now governs -----------
    # The first version computed Q1 over the zero-anchor repos and Q2 over every repo, and
    # never intersected them. The headline therefore came from repositories whose manifests
    # already parse -- the ones the feature is NOT for.
    print("Q2b THE JOIN  [POST-HOC: split the gap by whether the repo needed rescuing]\n")
    rescued_set = set(rescued)
    anchored = {c["case"] for c in per_case if not c["zero_before"]}
    # The verdict uses M-H, NOT pooled and NOT unweighted macro. Pooled is the estimator
    # this rewrite exists to discredit; unweighted macro lets a case with one score-3 paper
    # (`columnar`, +84.2pt off a single abstract) outvote one with twenty-one. M-H weights
    # each case by n1*n0/(n1+n0) -- by how much it can actually resolve.
    print(f"  {'repo set':28} {'cases':>6} {'pooled':>8} {'macro':>8} {'mac>=5':>8} {'M-H':>8}")
    resc_mh = 0.0
    for label, keep in (
        ("all", set(cases)),
        ("already had anchors", anchored),
        ("RESCUED — the feature's job", rescued_set),
    ):
        sub = [r for r in rows if r["case"] in keep]
        t = [r for r in sub if r["score"] >= 3]
        b = [r for r in sub if r["score"] < ACTIONABLE]
        cl = _case_cells(sub, "abs_nerdme")
        pooled = _hit_pct(t, "abs_nerdme") - _hit_pct(b, "abs_nerdme")
        if keep is rescued_set:
            resc_mh = _mh(cl)
        print(
            f"  {label:28} {len(_usable(cl)):>6} {pooled:>+7.1f} {_macro(cl):>+7.1f} "
            f"{_macro(cl, 5):>+7.1f} {_mh(cl):>+7.1f}"
        )
    rcl = _case_cells([r for r in rows if r["case"] in rescued_set], "abs_nerdme")
    pos, n = _n_positive(rcl)
    print(
        f"\n  rescued cases with ANY positive gap: {pos} of {n} usable "
        f"(of {len(rescued_set)} rescued, {len(rescued_set) - n} had no paper in both strata)"
    )
    print(
        f"  VERDICT ON THE FEATURE'S OWN TARGET (M-H): {resc_mh:+.1f}pt  ->  "
        f"{'PASS' if resc_mh >= 7.0 else 'FAIL — kill condition was +7.0pt'}\n"
    )

    # ---- Q2c a comparator that is not at its ceiling ------------------------------
    # "keywords score +0.2pt, so keywords are noise" is a saturation artifact: ~19 keywords
    # per case against ~4 spans means nearly every abstract contains at least one, and a
    # binary hit metric pinned at its ceiling cannot show a difference either way. The
    # honest control draws the SAME NUMBER of keyword terms the treatment received.
    print("Q2c SIZE-MATCHED KEYWORD CONTROL  [POST-HOC: a comparator off its ceiling]\n")
    rng = random.Random(20260816)
    draws = 200
    macros = []
    for _ in range(draws):
        sampled = {}
        for c in per_case:
            pool_kw = sorted(kw_by_case[c["case"]])
            k = min(c["nerdme"], len(pool_kw))
            sampled[c["case"]] = set(rng.sample(pool_kw, k)) if k else set()
        srows = [{**r, "s": _mentions(r["abstract"], sampled[r["case"]])} for r in rows]
        macros.append(_macro(_case_cells(srows, "s")))
    macros.sort()
    mean = sum(macros) / len(macros)
    nerdme_macro = _macro(cells)
    med = sorted(c["nerdme"] for c in per_case)[len(per_case) // 2]
    print(f"  {draws} seeded draws, |spans| keywords per case (median {med})")
    print(f"  size-matched keywords: mean {mean:+.1f}pt, 95% [{macros[5]:+.1f},{macros[194]:+.1f}]")
    print(f"  typed spans:           {nerdme_macro:+.1f}pt")
    print(
        f"  HONEST INCREMENT:      {nerdme_macro - mean:+.1f}pt  (not the '+36 vs +0.2' framing)\n"
    )

    # ---- Q3 / Q4 -------------------------------------------------------------------
    print("Q3  GROUNDED COVERAGE  [pre-registered: 12.3% -> 20-32% on actionable]\n")
    for label, sub in (("score 3", top), ("actionable >=2", good)):
        denom = len(sub) or 1
        m = 100 * sum(1 for r in sub if r["abs_manifest"] and r["relations"]) / denom
        u = 100 * sum(1 for r in sub if r["abs_union"] and r["relations"]) / denom
        print(f"  {label:16} manifest {m:>5.1f}%   union {u:>5.1f}%")
    print()

    print("Q4  CONCENTRATION  [pre-registered: 7 -> 14-20 cases, top-4 share < 70%]\n")
    for label, key in (("manifest", "abs_manifest"), ("union", "abs_union")):
        by: dict[str, int] = {}
        for r in good:
            by.setdefault(r["case"], 0)
            if r[key] and r["relations"]:
                by[r["case"]] += 1
        nz = {c: n for c, n in by.items() if n}
        carried = sum(nz.values())
        top4 = sum(sorted(nz.values(), reverse=True)[:4])
        print(
            f"  {label:10} {len(nz):>2} case(s), {carried:>3} claims, "
            f"top-4 share {100 * top4 / carried if carried else 0:.0f}%"
        )
    print()

    # ---- Q5, with the verdict the first version computed and never printed ---------
    print("Q5  ALIAS-TABLE BRIDGE  [pre-registered: method spans on >=15 cases AND")
    print("                         method gap >= library gap. BOTH required.]\n")
    with_m = [c for c in per_case if c["methods"] > 0]
    m_cells = _case_cells(rows, "abs_method")
    m_macro, l_macro = _macro(m_cells), _macro(_case_cells(rows, "abs_library"))
    cov_ok, gap_ok = len(with_m) >= 15, m_macro >= l_macro
    print(
        f"  cases yielding a `method` span: {len(with_m)}/{len(per_case)}"
        f"  (needed >=15 -> {'PASS' if cov_ok else 'FAIL'})"
    )
    print(f"  method-typed  macro {m_macro:+.1f}pt")
    print(f"  library-typed macro {l_macro:+.1f}pt  -> {'PASS' if gap_ok else 'FAIL'}")
    c, dlt = _loo_worst(m_cells)
    print(f"  load-bearing case for `method`: {c or 'n/a'} (removing it moves macro {dlt:+.1f}pt)")
    print(f"  CONJUNCTION VERDICT: {'PASS' if cov_ok and gap_ok else 'FAIL'}\n")

    # ---- diagnostics the first version lacked --------------------------------------
    print("Spans firing on NON-actionable abstracts (false-positive drivers):\n")
    for span, n in Counter(a for r in bad for a in r["abs_nerdme"]).most_common(8):
        print(f"  {span:30} {n:>4} below-2 abstracts")
    print()
    print("Per-case gap, typed spans (usable cases only):\n")
    for case, g in sorted(_case_gaps(cells).items(), key=lambda t: -t[1]):
        a, n1, b, n0 = cells[case]
        tag = "   <- rescued" if case in rescued_set else ""
        print(f"  {case:12} {g:>+7.1f}pt  (score3 {a}/{n1}, below2 {b}/{n0}){tag}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="NERdME typed-span anchor probe (P9)")
    ap.add_argument("--report", action="store_true", help="analyse cached spans only, no LLM")
    ap.add_argument("--refresh", action="store_true", help="re-extract even if cached")
    args = ap.parse_args()

    cases = sorted(p.stem for p in POOL.glob("*.json"))
    if args.report:
        if not CACHE.exists():
            raise SystemExit(f"no cached spans at {CACHE}; run without --report first")
        spans = json.loads(CACHE.read_text(encoding="utf-8"))
    else:
        spans = extract(cases, refresh=args.refresh)
    return analyse(spans)


